//! Validate `generated/{recipe}/` schemas and protos referenced in `goals.json`,
//! write `schema-manifest.json`, and emit `generated/proto_basenames.rs` and
//! `generated/goal_registry.rs`
//! (single source of truth for CLI goal name ↔ schema file ↔ proto file).

use std::fs;
use std::io;
use std::path::PathBuf;

const RECIPE_NAME: &str = "tdd";

fn main() -> io::Result<()> {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let goals_path = manifest_dir.join("goals.json");
    let generated = manifest_dir.join("generated");
    let recipe_dir = generated.join(RECIPE_NAME);

    println!("cargo:rerun-if-changed={}", goals_path.display());
    println!(
        "cargo:rerun-if-changed={}",
        manifest_dir.join("build.rs").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        manifest_dir.join("proto").display()
    );
    println!("cargo:rerun-if-changed={}", recipe_dir.display());

    let goals_raw = fs::read_to_string(&goals_path)?;
    let root: serde_json::Value = serde_json::from_str(&goals_raw)
        .map_err(|e| io::Error::new(io::ErrorKind::InvalidData, format!("goals.json: {}", e)))?;
    let goals_arr = root["goals"].as_array().ok_or_else(|| {
        io::Error::new(
            io::ErrorKind::InvalidData,
            "goals.json: missing \"goals\" array",
        )
    })?;

    for g in goals_arr {
        let schema = g["schema"]
            .as_str()
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, "goal entry: schema"))?;
        let proto = g["proto"]
            .as_str()
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, "goal entry: proto"))?;
        let schema_path = recipe_dir.join(schema);
        if !schema_path.is_file() {
            return Err(io::Error::new(
                io::ErrorKind::NotFound,
                format!("missing schema {}", schema_path.display()),
            ));
        }
        let proto_path = manifest_dir.join("proto").join(proto);
        if !proto_path.is_file() {
            return Err(io::Error::new(
                io::ErrorKind::NotFound,
                format!("missing proto {}", proto_path.display()),
            ));
        }
    }

    fs::create_dir_all(&generated)?;

    // Every object is built with its keys inserted in sorted order, so the file reads the same
    // whether `serde_json`'s map keeps insertion order or sorts. `preserve_order` is switched on by
    // any other crate in the same build that enables it, so with `json!` the key order — and the
    // committed file — changed with the set of packages a build happened to include.
    let manifest_goals: Vec<serde_json::Value> = goals_arr
        .iter()
        .map(|g| {
            let mut goal = serde_json::Map::new();
            for key in ["name", "proto", "schema"] {
                goal.insert(key.to_string(), g[key].clone());
            }
            serde_json::Value::Object(goal)
        })
        .collect();

    let mut manifest = serde_json::Map::new();
    manifest.insert(
        "goals".to_string(),
        serde_json::Value::Array(manifest_goals),
    );
    manifest.insert("version".to_string(), serde_json::Value::from(1));
    let manifest = serde_json::Value::Object(manifest);

    let manifest_path = generated.join("schema-manifest.json");
    fs::write(
        &manifest_path,
        serde_json::to_string_pretty(&manifest).unwrap(),
    )?;

    let mut proto_rs = String::from(
        "/// Generated by build.rs from goals.json — do not edit.\npub const EXPECTED_PROTO_BASENAMES: &[&str] = &[\n",
    );
    for g in goals_arr {
        let proto = g["proto"].as_str().expect("proto checked");
        proto_rs.push_str("    \"");
        proto_rs.push_str(proto);
        proto_rs.push_str("\",\n");
    }
    proto_rs.push_str("];\n");
    fs::write(generated.join("proto_basenames.rs"), proto_rs)?;

    let mut registry_rs = String::from(
        "/// Generated by build.rs from goals.json — do not edit.\npub const GOAL_SCHEMA_FILES: &[(&str, &str)] = &[\n",
    );
    for g in goals_arr {
        let name = g["name"]
            .as_str()
            .ok_or_else(|| io::Error::new(io::ErrorKind::InvalidData, "goal entry: name"))?;
        let schema = g["schema"].as_str().expect("schema checked");
        registry_rs.push_str("    (\"");
        registry_rs.push_str(name);
        registry_rs.push_str("\", \"");
        registry_rs.push_str(RECIPE_NAME);
        registry_rs.push('/');
        registry_rs.push_str(schema);
        registry_rs.push_str("\"),\n");
    }
    registry_rs.push_str("];\n");
    fs::write(generated.join("goal_registry.rs"), registry_rs)?;

    println!(
        "tddy-workflow-recipes: wrote {}, proto_basenames.rs, goal_registry.rs; validated schemas in {}",
        manifest_path.display(),
        recipe_dir.display()
    );

    Ok(())
}
